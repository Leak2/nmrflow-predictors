"""核素常量、参考物质、去耦策略表。

本模块是最底层，不依赖 rdkit / numpy，避免 predict 与 spin 之间循环 import。
"""

from __future__ import annotations

from dataclasses import dataclass

# ---------------------------------------------------------------------------
# 旋磁比 γ/2π，单位 MHz/T（1 特斯拉下的共振频率）
# 全部以 1H 为锚点换算其它核的频率
# ---------------------------------------------------------------------------
GAMMA_MHZ_T: dict[str, float] = {
    "1H": 42.57747892,
    "19F": 40.052136,
    "13C": 10.7084,
    "31P": 17.2354,
}

REFERENCE_NUCLEUS = "1H"


@dataclass(frozen=True)
class NucleusInfo:
    """一个可观测核素的物理常量。"""

    symbol: str          # "1H" / "13C" / "19F" / "31P"
    element: str         # "H" / "C" / "F" / "P"
    spin: float          # 自旋量子数 I
    abundance: float     # 天然丰度
    reference: str       # 化学位移参考物质
    display: str         # 报告里显示的核名，例如 "13C"


NUCLEI: dict[str, NucleusInfo] = {
    "1H": NucleusInfo("1H", "H", 0.5, 0.999885, "TMS", "1H"),
    "13C": NucleusInfo("13C", "C", 0.5, 0.0107, "TMS", "13C"),
    "19F": NucleusInfo("19F", "F", 0.5, 1.0, "CFCl3", "19F"),
    "31P": NucleusInfo("31P", "P", 0.5, 1.0, "85% H3PO4", "31P"),
}

# 元素 -> 可观测核素
ELEMENT_TO_NUCLEUS: dict[str, str] = {
    info.element: sym for sym, info in NUCLEI.items()
}

# 谱图输出顺序（与文献报道顺序一致）
NUCLEUS_ORDER: tuple[str, ...] = ("1H", "19F", "31P", "13C")

# ---------------------------------------------------------------------------
# 默认去耦策略：观测核 -> 被宽带去耦的核集合
# 13C 默认对 1H 去耦（全单峰），但保留与 F / P 的耦合；
# 31P 默认对 1H 去耦；19F 不去耦（要看到 H-F 裂分）；1H 不去耦。
# ---------------------------------------------------------------------------
DECOUPLE_DEFAULT: dict[str, tuple[str, ...]] = {
    "1H": (),
    "19F": (),
    "31P": ("1H",),
    "13C": ("1H",),
}

# ---------------------------------------------------------------------------
# 基本物理常量（Da）
# ---------------------------------------------------------------------------
PROTON_MASS = 1.00727646677    # [M+H]+ 加的是质子，不是氢原子
ELECTRON_MASS = 0.00054857990907

# ---------------------------------------------------------------------------
# 谱图仿真默认值
# ---------------------------------------------------------------------------
DEFAULT_PROTON_MHZ = 400.0
DEFAULT_SOLVENT = "CDCl3"

# 自旋哈密顿量精确对角化的自旋数上限。按 M 分块后每块最大 C(n,n/2)，
# n=10 时 252 维，既覆盖了常见的强耦合脂肪族多重峰，也不会让单张图变慢。
MAX_EXACT_SPINS = 10

# 强耦合判据：Δν(Hz) / |J| < STRONG_COUPLING_RATIO 时视为强耦合
STRONG_COUPLING_RATIO = 10.0

# 默认线宽 FWHM（Hz）
DEFAULT_FWHM = {
    "1H": 0.8,
    "13C": 1.5,
    "19F": 1.0,
    "31P": 2.0,
}
LABILE_FWHM = 4.5          # 活泼氢（OH/NH/SH/COOH）加宽
VAGUE_FWHM = 12.0          # 查表未命中、置信度低时的宽峰（¹⁹F/³¹P 的未知环境）

# 置信度为 low 时的展宽上限。这里必须按核分开：12 Hz 对 ¹⁹F/³¹P 是“宽峰”，
# 对 400 MHz 的 ¹H 却是 0.03 ppm，足以把 J=7 Hz 的四重峰糊成一个宽包。
