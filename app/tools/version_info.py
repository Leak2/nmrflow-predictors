"""生成 / 校验 ``NMR-Predictor.exe`` 的 Windows 版本资源（VS_VERSIONINFO）。

为什么需要
----------
exe 是 PyInstaller 打的，默认**不带**版本资源。结果是：
右键 → 属性 → 详细信息 是空白；任务管理器里只显示文件名；用户报问题时
"你用的是哪一版"只能靠猜（包里也没有版本号可见的地方）。
0.2.7 起把版本资源写进 exe，来源只有一个——``app/nmrflow/__init__.py`` 的
``__version__``，不在这里再抄一遍版本号。

做法
----
PyInstaller 的 ``--version-file`` 接收一个**Python 字面量文件**，内容是
``VSVersionInfo(...)``，它会用内置的若干类去 eval。所以这里只是拼一段文本，
不需要编译资源脚本，也不需要 MSVC。

两个容易踩的点
--------------
1. 文件读取编码。PyInstaller 读这个文件的方式在不同版本间变过，中文直接写进去
   有被按 cp1252/cp936 解码的风险。这里把非 ASCII 字符全部写成 ``\\uXXXX``
   转义，**文件本身是纯 ASCII**，任何解码方式都得到同一串字符。
2. ``FileVersion`` 必须是 ``a.b.c.d`` 四个整数。``0.2.7`` 补成 ``0.2.7.0``；
   带后缀的（如 ``0.2.8rc1``）会把非数字尾巴丢掉，只在 ``Comments`` 里保留原串。

用法
----
    python tools/version_info.py --out build/pyinstaller/version_info.txt
    python tools/version_info.py --check dist/nmrflow-0.2.7-portable/NMR-Predictor.exe
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

COMPANY = "nmrflow"
INTERNAL_NAME = "NMR-Predictor"
ORIGINAL_FILENAME = "NMR-Predictor.exe"
COPYRIGHT = "BSD 3-Clause License"
COMMENTS = "Portable offline build. See REPRODUCE.md / CHANGELOG.md."
#: "NMR 谱图预测（SMILES → NMR + HRMS）" 的转义写法——保持文件纯 ASCII
FILE_DESCRIPTION = (
    "NMR \u8c31\u56fe\u9884\u6d4b"
    " (SMILES \u2192 NMR + HRMS)"
)


def read_version(root: Path = ROOT) -> str:
    """从 ``nmrflow/__init__.py`` 取版本号——单一口径，不在别处重复。"""
    init = root / "nmrflow" / "__init__.py"
    if not init.exists():
        raise SystemExit(f"找不到 {init}")
    match = re.search(r'^__version__\s*=\s*["\']([^"\']+)["\']',
                      init.read_text(encoding="utf-8"), re.M)
    if not match:
        raise SystemExit(f"{init} 里没有 __version__")
    return match.group(1)


def version_tuple(version: str) -> tuple[int, int, int, int]:
    """``0.2.7`` → ``(0, 2, 7, 0)``；``0.2.8rc1`` → ``(0, 2, 8, 0)``。

    只认开头那段点分数字。**不能**用 "把字符串里所有数字抽出来" 的写法：
    ``0.2.8rc1`` 会抽出 ``(0, 2, 8, 1)``，属性页就变成 "0.2.8.1"——
    多的那个 1 是 rc1 里的 1，不是修订号。
    """
    match = re.match(r"\s*(\d+)\.(\d+)\.(\d+)(?:\.(\d+))?", version)
    if not match:
        raise SystemExit(f"版本号 {version!r} 不是 x.y.z 形式")
    major, minor, patch, build = match.groups()
    return (int(major), int(minor), int(patch), int(build or 0))


def render(version: str) -> str:
    """PyInstaller ``--version-file`` 的内容（纯 ASCII）。"""
    ver = version_tuple(version)
    dotted = ".".join(str(n) for n in ver)
    strings = [
        ("CompanyName", COMPANY),
        ("FileDescription", FILE_DESCRIPTION),
        ("FileVersion", dotted),
        ("InternalName", INTERNAL_NAME),
        ("LegalCopyright", COPYRIGHT),
        ("OriginalFilename", ORIGINAL_FILENAME),
        ("ProductName", COMPANY),
        ("ProductVersion", dotted),
        ("Comments", f"{COMMENTS} version={version}"),
    ]
    # 两个语言块：zh-CN(0x0804) 与 en-US(0x0409)，都用 Unicode 代码页(0x04b0)。
    # 只写一个表也能用，但资源查看器的"语言"列会显示 0x0409 之外的东西。
    tables = []
    for lang in ("080404b0", "040904b0"):
        body = ",\n".join(
            f"          StringStruct({k!r}, {ascii(v)})" for k, v in strings
        )
        tables.append(
            "      StringTable(\n"
            f"        {lang!r},\n"
            "        [\n"
            f"{body}\n"
            "        ]\n"
            "      )"
        )
    return (
        "# Generated by tools/version_info.py -- do not edit by hand.\n"
        f"# version = {version}\n"
        "VSVersionInfo(\n"
        "  ffi=FixedFileInfo(\n"
        f"    filevers={ver!r},\n"
        f"    prodvers={ver!r},\n"
        "    mask=0x3f,\n"
        "    flags=0x0,\n"
        "    OS=0x40004,\n"
        "    fileType=0x1,\n"
        "    subtype=0x0,\n"
        "    date=(0, 0)\n"
        "  ),\n"
        "  kids=[\n"
        "    StringFileInfo([\n"
        + ",\n".join(tables)
        + "\n    ]),\n"
        "    VarFileInfo([VarStruct('Translation', [2052, 1200, 1033, 1200])])\n"
        "  ]\n"
        ")\n"
    )


def write(version: str, out: Path) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(version), encoding="ascii")
    return out


def describe(exe: Path) -> dict[str, str]:
    """用 ``pefile`` 把 exe 里真正写进去的版本资源读出来。

    打包后必须核对一遍：``--version-file`` 拼错时 PyInstaller 有时只是警告，
    产出的 exe 照样能跑，只是没有版本信息——这种"静默失效"只能在成品上查。
    """
    try:
        import pefile
    except ImportError:
        raise SystemExit("需要 pefile 才能校验（pip install pefile）") from None

    pe = pefile.PE(str(exe), fast_load=True)
    pe.parse_data_directories(
        directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_RESOURCE"]]
    )
    for entry in getattr(pe, "FileInfo", []) or []:
        for table in entry:
            for item in getattr(table, "StringTable", []) or []:
                out: dict[str, str] = {}
                for name, value in item.entries.items():
                    out[name.decode("utf-8", "replace")] = (
                        value.decode("utf-8", "replace")
                    )
                if out:
                    return out
    return {}


def main() -> int:
    ap = argparse.ArgumentParser(description="exe 版本资源：生成 / 校验")
    ap.add_argument("--out", type=Path, help="写出版本资源文件")
    ap.add_argument("--check", type=Path, metavar="EXE", help="读取 exe 里的版本资源")
    ap.add_argument("--version", help="覆盖版本号（默认取 nmrflow.__version__）")
    args = ap.parse_args()

    version = args.version or read_version()
    if args.out:
        path = write(version, args.out)
        print(f"wrote {path} (version {version})")
        return 0
    if args.check:
        info = describe(args.check)
        if not info:
            print(f"{args.check}: 没有版本资源", file=sys.stderr)
            return 1
        for key in ("FileVersion", "ProductVersion", "ProductName",
                    "FileDescription", "LegalCopyright"):
            print(f"  {key:<16}{info.get(key, '-')}")
        if info.get("FileVersion") != ".".join(map(str, version_tuple(version))):
            print(f"  ! 期望 {version_tuple(version)}，实际 "
                  f"{info.get('FileVersion')}", file=sys.stderr)
            return 1
        return 0
    print(version)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
